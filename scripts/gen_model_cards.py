def render(template, repo_kind, size, cur, root_cur):
    t = load(cur["train_config"])
    org = root_cur["hf_org"]
    repo = cur["hf_repos"]["gguf" if repo_kind == "gguf" else "safetensors"]
    gguf_file = "maris3d-%s-Q8_0.gguf" % size
    folder = os.path.join(ROOT, "hf", repo)
    sc = cur["score"]
    basis = cur["gate_basis"]
    shown = cur.get("score_repair2") if basis == "repair2" else sc
    missing = [k for k, a in cur["artifacts"].items() if a is None and ((repo_kind == "gguf" and k.startswith("gguf")) or (repo_kind == "st" and k.startswith("safetensors")))]
    if repo_kind == "gguf":
        # Q4_K_M is planned but not required for the card to be valid; Q8_0 is the evaluated file
        missing = [m for m in missing if m != "gguf-q4_k_m"]
    status = "release %s candidate, not yet published." % cur["version"]
    if missing:
        status += " Draft: the weights file is not staged yet (%s)." % ", ".join(missing)
    sizes = ", ".join(v["public_name"] for v in root_cur["sizes"].values())
    ctx = {
        "base_model_yaml": cur["base_model"] if repo_kind == "st" else "%s/maris3d-%s" % (org, size),
        "relation_line": ("base_model_relation: finetune\n" if repo_kind == "st" else "base_model_relation: quantized\n"),
        "library_name": "transformers" if repo_kind == "st" else "gguf",
        "extra_tags": "" if repo_kind == "st" else "- gguf\n- llama-cpp\n- ollama\n",
        "public_name": cur["public_name"], "pass_pct": shown["pass_pct"], "run_pct": shown["run_pct"],
        "score_basis_short": "bare model" if basis == "bare" else "with repair loop",
        "repo_suffix": " (GGUF)" if repo_kind == "gguf" else "",
        "intro": ("Quantized GGUF (Q8_0) of %s for llama.cpp and Ollama." % cur["public_name"]) if repo_kind == "gguf" else
                 ("%s is a small language model fine-tuned from %s to turn a text request into Blender tool calls (merged bfloat16 weights, safetensors)." % (cur["public_name"], cur["base_model"])),
        "status_line": status, "sizes_list": sizes, "version": cur["version"], "base_model": cur["base_model"], "parameters": cur["parameters"],
        "lora_rank": t["lora_parameters"]["rank"], "lora_scale": t["lora_parameters"]["scale"], "lora_layers": t["num_layers"],
        "train_rows": "{:,}".format(t["train_rows"]), "valid_rows": t["valid_rows"], "val_loss": t["final_val_loss"],
        "context_trained": cur["context_trained"], "context_max": "{:,}".format(cur["context_max"]), "memory_gb": cur["memory_gb"],
        "blender": "5.2.2", "results_table": results_table(size, cur), "results_notes": results_notes(size, cur),
        "usage_block": (USAGE_GGUF.format(name="maris3d-%s" % size, file=gguf_file) if repo_kind == "gguf" else
                        USAGE_ST.format(org=org, repo=repo)),
        "train_summary": "%s iterations, batch size %s x %s accumulation, learning rate %s, max sequence length %s, optimizer %s, seed %s" % (
            "{:,}".format(t["iters"]), t["batch_size"], t["grad_accumulation_steps"], t["learning_rate"], t["max_seq_length"], t["optimizer"], t["seed"]),
        "train_config_name": os.path.basename(cur["train_config"]),
        "passed": sc["passed"], "n": sc["n"], "extra_limits": "",
        "files_table": files_table(folder, root_cur, cur, "gguf" if repo_kind == "gguf" else "st"),
    }
    if basis == "repair2":
        ctx["extra_limits"] = "- Bare-model pass rate (%s%%) is just under the 60%% quality target used for this project; the stated headline needs the retry loop (the caller feeds the failed check back, up to 2 times).\n" % sc["pass_pct"]
    text = re.sub(r"\{\{(\w+)\}\}", lambda m: str(ctx[m.group(1)]), template)
    return text


def family_table(root_cur):
    rows = ["| | " + " | ".join(v["public_name"] for v in root_cur["sizes"].values()) + " |", "|---|" + "---|" * len(root_cur["sizes"])]

    def line(label, f):
        rows.append("| %s | %s |" % (label, " | ".join(f(k, v) for k, v in root_cur["sizes"].items())))
    line("Parameters", lambda k, v: v["parameters"])
    line("Base model", lambda k, v: "`%s`" % v["base_model"])
    line("Context (trained / architecture max)", lambda k, v: "%s / %s" % ("{:,}".format(v["context_trained"]), "{:,}".format(v["context_max"])))
    line("Formats", lambda k, v: ", ".join(n for n, a in v["artifacts"].items() if a) + (" (+ Q4_K_M planned)" if not v["artifacts"].get("gguf-q4_k_m") else ""))
    line("GGUF Q8_0 file", lambda k, v: fmt_bytes(v["artifacts"]["gguf-q8_0"]["bytes"]))
    line("Benchmark pass, bare model", lambda k, v: "%s%% (%d/%d)" % (v["score"]["pass_pct"], v["score"]["passed"], v["score"]["n"]))
    line("Benchmark pass, with repair loop", lambda k, v: ("%s%% (%d/%d)" % (v["score_repair2"]["pass_pct"], v["score_repair2"]["passed"], v["score_repair2"]["n"])) if v.get("score_repair2") else "not measured")
    line("Memory (Q8_0, measured)", lambda k, v: "about %s GB" % v["memory_gb"])
    line("Speed (tok/s, see result files for machine)", lambda k, v: ("%.1f (%s)" % (v["score"]["tok_s"], v["score"]["tok_s_machine"])) if v["score"].get("tok_s") else "not measured")
    line("Release", lambda k, v: v["version"])
    return "\n".join(rows)


def build(root_cur):
    template = open(os.path.join(ROOT, "MODEL_CARD.md")).read()
    out = {}
    for size, cur in root_cur["sizes"].items():
        for kind in ("st", "gguf"):
            repo = cur["hf_repos"].get("gguf" if kind == "gguf" else "safetensors")
            if not repo:
                continue
            rel = os.path.join("hf", repo, "README.md")
            p = os.path.join(ROOT, rel)
            if os.path.exists(p) and "hand-curated" in open(p).read():
                continue  # hand-written card, maintained by hand (e.g. the GGUF release card)
            out[rel] = render(template, kind, size, cur, root_cur)
    readme = os.path.join(ROOT, "README.md")
    if os.path.exists(readme):
        r = open(readme).read()
        if TABLE_BEGIN in r and TABLE_END in r:
            a, rest = r.split(TABLE_BEGIN, 1)
            _, b = rest.split(TABLE_END, 1)
            out["README.md"] = a + TABLE_BEGIN + "\n" + family_table(root_cur) + "\n" + TABLE_END + b
    return out


def main(argv=None):
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    root_cur = load("release/CURRENT.json")
    stale = []
    for rel, text in build(root_cur).items():
        p = os.path.join(ROOT, rel)
        if check:
            if not os.path.exists(p) or open(p).read() != text:
                stale.append(rel)
        else:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w") as f:
                f.write(text)
    for size, cur in root_cur["sizes"].items():
        for repo in cur["hf_repos"].values():
            folder = os.path.join(ROOT, "hf", repo)
            if check:
                sums = hf_stage.read_sums(folder)
                if sums is None:
                    stale.append("hf/%s/SHA256SUMS missing" % repo)
                    continue
                for a in cur["artifacts"].values():
                    if a and os.path.dirname(a["path"]) == "hf/" + repo and sums.get(os.path.basename(a["path"])) != a["sha256"]:
                        stale.append("hf/%s/SHA256SUMS disagrees with CURRENT.json for %s" % (repo, os.path.basename(a["path"])))
            else:
                hf_stage.write_sums_from(folder, {os.path.basename(a["path"]): a["sha256"] for a in cur["artifacts"].values() if a and os.path.dirname(a["path"]) == "hf/" + repo})
    if check:
        print("\n".join("stale: " + s for s in stale) or "model cards, README table and checksums are up to date")
        return 1 if stale else 0
    print("cards written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
