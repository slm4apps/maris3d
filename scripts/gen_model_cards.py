"""Generate hf/*/README.md (one card per Hugging Face repo) and the size table of README.md from ONE template (MODEL_CARD.md),
release/CURRENT.json and the result JSON files. Numbers are never typed by hand.

    python3 scripts/gen_model_cards.py            # write cards, then (if weights are present) refresh SHA256SUMS
    python3 scripts/gen_model_cards.py --check    # exit 1 if any card, README table or SHA256SUMS is stale (used by CI)
"""
import json, os, re, sys

# RETIRED for v0.1 (9 Nov 2026): this generator targets the old per-size JSON-model
# pipeline and the removed MODEL_CARD.md template. The ONLY public card for v0.1 is
# hf/Maris3D-Blender/README.md, maintained by hand. Refuse to run so nothing can
# be generated from the stale template ever again.
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
if __name__ == "__main__" and not os.path.exists(os.path.join(ROOT, "MODEL_CARD.md")):
    print("gen_model_cards.py is retired: MODEL_CARD.md is gone; the only v0.1 card is "
          "hf/Maris3D-Blender/README.md (hand-maintained). Nothing generated.")
    sys.exit(0)

sys.path.insert(0, os.path.join(ROOT, "scripts"))
import hf_stage  # noqa: E402

TABLE_BEGIN, TABLE_END = "<!-- BEGIN SIZE TABLE (generated by scripts/gen_model_cards.py) -->", "<!-- END SIZE TABLE -->"


def load(rel):
    with open(os.path.join(ROOT, rel)) as f:
        return json.load(f)


def fmt_bytes(n):
    return "%.2f GB" % (n / 1e9) if n >= 1e9 else "%.0f MB" % (n / 1e6)


def result_rows(size, cur):
    rows = []
    for key, label in (("bare", "bare model"), ("repair2", "with repair loop (2 retries)")):
        rel = cur["results"].get(key)
        if rel:
            rows.append((label, load(rel)["summary"], rel))
    return rows


def results_table(size, cur):
    out = ["| Setting | Pass % | Passed | Run % | L1 | L2 | L3 | L4 | tok/s |", "|---|---|---|---|---|---|---|---|---|"]
    srcs = []
    for label, s, rel in result_rows(size, cur):
        lv = s["by_level"]
        speed = ("%.1f (%s)" % (s["tok_s"], s.get("tok_s_machine", "n/a"))) if s.get("tok_s") else "n/a"
        out.append("| %s | **%s** | %d / %d | %s | %s | %s | %s | %s | %s |" % (
            label, s["pass_pct"], s["passed"], s["n"], s["run_pct"], lv["1"], lv["2"], lv["3"], lv["4"], speed))
        srcs.append("<!-- source: %s -->" % rel)
    return "\n".join(out + srcs)


def results_notes(size, cur):
    notes = ["Scores were measured on the **Q8_0 GGUF file** of this release (greedy decoding, 4096 context, Blender {}). Pass % is the share of the 206 prompts whose scene check held; Run % is the share whose script executed.".format("5.2.2")]
    if cur.get("gate_note"):
        notes.append(cur["gate_note"])
    if size == "1.5b":
        notes.append("Speed depends on the machine; the two measured values (about 27 tok/s on an Apple-silicon Mac, about 9 tok/s on a CPU-only server) are in the result files.")
    return "\n\n".join(notes)


def files_table(folder, cur_all, size_cur, kind):
    rows = ["| File | Size | SHA-256 |", "|---|---|---|"]
    arts = {os.path.basename(a["path"]): a for a in size_cur["artifacts"].values() if a}
    for n in hf_stage.staged_files(folder):
        if n == "README.md":
            continue
        p = os.path.join(folder, n)
        if n in arts:
            size, h = arts[n]["bytes"], arts[n]["sha256"]
        elif os.path.exists(p):
            size, h = os.path.getsize(p), hf_stage.sha256_file(p)
        else:
            continue
        rows.append("| `%s` | %s | `%s` |" % (n, fmt_bytes(size), h))
    for k, a in size_cur["artifacts"].items():
        if a is None and ((kind == "gguf" and k.startswith("gguf")) or (kind == "st" and k.startswith("safetensors"))):
            rows.append("| *(%s)* | not yet staged | see release/STATUS.md |" % k)
    return "\n".join(rows)


